<script>
document.getElementById('contact-form').addEventListener('submit', function(e) {
  e.preventDefault();

  const fname    = document.getElementById('f-name').value.trim();
  const lname    = document.getElementById('f-lname').value.trim();
  const email    = document.getElementById('f-email').value.trim();
  const phone    = document.getElementById('f-phone').value.trim();
  const service  = document.getElementById('f-service').value;
  const date     = document.getElementById('f-date').value;
  const pax      = document.getElementById('f-pax').value;
  const dest     = document.getElementById('f-dest').value.trim();
  const msg      = document.getElementById('f-msg').value.trim();

  // Basic validation
  if (!fname || !lname || !email || !phone || !service || !msg) {
    alert('Please fill in all required fields.');
    return;
  }

  // Build WhatsApp message
  const lines = [
    '-> *New Booking Enquiry — Tour & Transport Solution*',
    '',
    `-> *Name:* ${fname} ${lname}`,
    `-> *Email:* ${email}`,
    `-> *Phone:* ${phone}`,
    `-> *Service:* ${service}`,
    date  ? `-> *Travel Date:* ${date}` : '',
    pax   ? `-> *Travellers:* ${pax}` : '',
    dest  ? `-> *Destination/Route:* ${dest}` : '',
    `-> *Details:* ${msg}`,
  ].filter(Boolean).join('\n');

//   const waNumber = '8801632221259';
  const waNumber = '8801403526057'; // country code + number, no + or spaces
  const waURL = `https://wa.me/${waNumber}?text=${encodeURIComponent(lines)}`;

  // Show success message
  document.getElementById('contact-form').style.display = 'none';
  document.getElementById('form-success').style.display = 'block';

  // Open WhatsApp
  window.open(waURL, '_blank');
});
</script>

